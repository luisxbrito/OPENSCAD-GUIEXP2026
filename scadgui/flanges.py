def asme_face_height(cls: int) -> float:
    """Altura del resalte (ASME B16.5-2013, párr. 6.4.1)."""
    return 2.0 if cls in (150, 300) else 7.0


def en_face_height(dn: int) -> float:
    """f1 de la tabla 8 de EN 1092-1:2018: 2 mm hasta DN 32, 3 hasta DN 250, 4 hasta DN 500 y 5 desde DN 600."""
    return 2.0 if dn <= 32 else 3.0 if dn <= 250 else 4.0 if dn <= 500 else 5.0


def inch_mm(text: str) -> float:
    """'1 1/8' (pulgadas) → milímetros."""
    whole, _, frac = text.partition(" ")
    value = Fraction(whole) + (Fraction(frac) if frac else 0) if "/" not in whole else Fraction(whole)
    return round(float(value) * INCH, 2)


