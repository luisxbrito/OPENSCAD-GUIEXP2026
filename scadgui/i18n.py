def tr(text: str, lang: Optional[str] = None) -> str:
    """Traduce un texto al idioma activo o especificado. Si no existe traducción, devuelve el texto original."""
    target_lang = lang or _current_lang
    if target_lang == "es":
        return text
    table = TRANSLATIONS.get(target_lang, {})
    return table.get(text, text)
